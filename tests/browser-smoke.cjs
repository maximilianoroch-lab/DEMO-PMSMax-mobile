const {chromium}=require('playwright');
const assert=require('node:assert/strict');
(async()=>{
 const browser=await chromium.launch({headless:true});
 const instruments='SPY ACWI QQQ FXI XLV GLD VEA EEM EWZ ALUA BBAR BHIP BMA CEPU COME CRES GGAL PAMP SUPV TGSU2 TXAR YPFD AO28 AO29 AN29 GD35 GD38 GD41 BTC ETH ADA SOL XRP AAPL AMD AMZN AVGO BRKB DISN GLOB GOOGL HD JNJ JPM KO LLY LAC LAR LRCX MCD MELI META MSFT NKE NU NVDA PBR PEP PFE T TSLA V VIST WMT CASH'.split(' ');
 assert.equal(instruments.length,65,'Fixtures must use exactly 65 DEMO tickers');
 const accounts=['SANTANDER','BBVA','CRITERIA 1234','CRITERIA 5678','ADCAP','IOL','GALICIA','BINANCE'];
 const csv=['Ticker,Cantidad total,Precio USD indicativo,Valor USD indicativo,'+accounts.join(','),...instruments.map(t=>[t,100,10,1000,100,0,0,0,0,0,0,0].join(','))].join('\n');
 const page=await browser.newPage();
 const errors=[];page.on('pageerror',e=>errors.push(e.message));
 await page.route('https://docs.google.com/**',route=>route.fulfill({status:200,body:csv,headers:{'content-type':'text/csv','access-control-allow-origin':'*'}}));
 await page.goto('file://'+process.cwd()+'/index.html',{waitUntil:'domcontentloaded'});
 await page.locator('#summary .value').first().waitFor({timeout:15000});
 const displayed=await page.locator('#summary').innerText();
 assert.match(displayed,/65.000/);
 assert.match(displayed,/65/);
 await page.locator('[data-page="diversificacion"]').click();
 assert.equal(await page.locator('#diversificacion.active').count(),1);
 await page.locator('[data-page="posiciones"]').click();
 assert.match(await page.locator('#positionTable').innerText(),/AAPL/);
 await page.locator('[data-page="custodia"]').click();
 assert.match(await page.locator('#custodians').innerText(),/SANTANDER/);
 await page.locator('[data-page="resumen"]').click();
 await page.locator('#voiceSummaryBtn').click();
 assert.match(await page.locator('#voiceSummaryText').innerText(),/65 instrumentos/);
 if(errors.length)throw Error('JavaScript runtime errors: '+errors.join(';'));
 const denied=await browser.newPage();
 await denied.route('https://docs.google.com/**',route=>route.fulfill({status:503,body:'unavailable',headers:{'access-control-allow-origin':'*'}}));
 await denied.goto('file://'+process.cwd()+'/index.html',{waitUntil:'domcontentloaded'});
 await denied.waitForFunction(()=>document.getElementById('status').textContent.includes('no disponible'),null,{timeout:15000});
 assert.match(await denied.locator('#summary').innerText(),/No se muestran datos/);
 await denied.close();await browser.close();
 console.log('Browser smoke: validated V5 inventory, 65 fictitious assets, navigation, custody, voice and fail-closed source errors.');
})().catch(e=>{console.error(e);process.exit(1)});
